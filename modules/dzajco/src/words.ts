/** Strips zero-width spaces, folds to NFC lowercase and drops repeats, keeping the first occurrence. */
export function normalizeWords(words: readonly string[]): string[] {
  const seen = new Set<string>();
  for (const word of words) {
    const folded = word.replaceAll("\u200b", "").normalize("NFC").trim().toLowerCase();
    if (folded.length > 0) seen.add(folded);
  }
  return [...seen];
}

export const DZAJCO_WORDS: readonly string[] = normalizeWords(SOURCE_WORDS);
